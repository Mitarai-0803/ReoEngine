#pragma once

//============================================================================
//! @file   FontManager.h
//! @brief  フォント管理の宣言
//============================================================================
namespace Font {
//-----------------------------------------------------------
//! @brief フォントインデックス（新しく使うフォントがあればここに追記）
//-----------------------------------------------------------
enum FontIndex
{
    FONT_MIN             = -1,    //!< フォント最小値
    FONT_NOTO_SANS_INDEX = 0,     //!< Noto Sans Japanese
    FONT_MAX                      //!< フォント最大数
};

//-----------------------------------------------------------
//! @brief フォントの初期化
//-----------------------------------------------------------
void FontInit();

//-----------------------------------------------------------
//! @brief フォントの解放
//-----------------------------------------------------------
void FontExit();

//-----------------------------------------------------------
//! @brief フォントハンドル取得
//-----------------------------------------------------------
//! @param font_index フォントインデックス
//! @return フォントハンドル
//-----------------------------------------------------------
int GetFont(int font_index);

//-----------------------------------------------------------
//! @class FontManager
//! @brief フォント管理クラス
//! @details フォントのロード・アンロードを行う
//-----------------------------------------------------------
class FontManager
{
public:
    //-----------------------------------------------------------
    //! @brief フォント初期化
    //-----------------------------------------------------------
    static void Init();

    //-----------------------------------------------------------
    //! @brief フォント解放
    //-----------------------------------------------------------
    static void Exit();

    //-----------------------------------------------------------
    //! @brief フォントハンドル取得
    //! @param [in] font_index フォントインデックス
    //! @return フォントハンドル
    //-----------------------------------------------------------
    static int GetFont(int font_index);

private:
    static int m_font_handles[FONT_MAX];    //!< フォントハンドル配列
};
}    // namespace Font
