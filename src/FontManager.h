#pragma once

//============================================================================
//! @file   FontManager.h
//! @brief  フォント管理ユーティリティの宣言
//============================================================================
namespace Font {
//-----------------------------------------------------------
//! @brief フォントインデックス
//-----------------------------------------------------------
enum FontIndex
{
    FONT_SIZE_70_INDEX = 0,    //!< フォントサイズ 70 のインデックス
    FONT_SIZE_50_INDEX,        //!< フォントサイズ 50 のインデックス
    FONT_SIZE_40_INDEX,        //!< フォントサイズ 40 のインデックス
    FONT_SIZE_30_INDEX,        //!< フォントサイズ 30 のインデックス
    FONT_SIZE_25_INDEX,        //!< フォントサイズ 25 のインデックス
    FONT_SIZE_10_INDEX,        //!< フォントサイズ 10 のインデックス
    FONT_MAX                   //!< フォントの最大数
};

//-----------------------------------------------------------
//! @brief フォント初期化
//-----------------------------------------------------------
void FontInit();

//-----------------------------------------------------------
//! @brief フォント解放
//-----------------------------------------------------------
void FontExit();

//-----------------------------------------------------------
//! @brief フォントハンドル取得
//! @param font_index フォントインデックス
//! @return フォントハンドル
//-----------------------------------------------------------
int GetFont(int font_index);

//-----------------------------------------------------------
//! @class FontManager
//! @brief フォントを管理するクラスの宣言
//! @details フォントハンドル配列をプライベートメンバとして保持し、
//!          初期化・解放・取得処理を提供する
//-----------------------------------------------------------
class FontManager
{
public:
    //-----------------------------------------------------------
    //! @brief フォント初期化
    //-----------------------------------------------------------
    static void Init();

    //-----------------------------------------------------------
    //! @brief フォント解放
    //-----------------------------------------------------------
    static void Exit();

    //-----------------------------------------------------------
    //! @brief フォントハンドル取得
    //! @param [in] font_index フォントインデックス
    //! @return フォントハンドル
    //-----------------------------------------------------------
    static int GetFont(int font_index);

private:
    static int m_font_handles[FONT_MAX];    //!< フォントハンドル配列
};
}    // namespace Font
