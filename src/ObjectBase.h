#pragma once
//============================================================================
//! @file   ObjectBase.h
//! @brief  ゲームオブジェクトの宣言
//! @details コンポーネントを保持し、ライフサイクルを管理するクラスの宣言
//! @author レオ
//============================================================================
#include "ComponentBase.h"    // コンポーネント基底クラス
#include <vector>             // コンテナヘッダ
#include <memory>             // スマートポインタ
#include <string>             // 文字列
#include <type_traits>        // 型特性

namespace Object {
//============================================================================
//! @class ObjectBase
//! @brief ゲームオブジェクトの基底クラス
//! @details コンポーネントを保持し、ライフサイクル（Init/Update/Draw/End）を管理する
//============================================================================
class ObjectBase
{
public:
    //-----------------------------------------------------------
    //! @brief コンストラクタ
    //-----------------------------------------------------------
    ObjectBase() = default;

    //-----------------------------------------------------------
    //! @brief デストラクタ
    //-----------------------------------------------------------
    ~ObjectBase();

    //-----------------------------------------------------------
    //! @brief 名前取得
    //! @return オブジェクト名
    //-----------------------------------------------------------
    std::string GetName() const { return m_name; }

    //-----------------------------------------------------------
    //! @brief 名前設定
    //! @param [in] n 設定する名前
    //-----------------------------------------------------------
    void SetName(const std::string& n) { m_name = n; }

    //-----------------------------------------------------------
    //! @brief コンポーネント追加
    //! @tparam T 追加するコンポーネント型
    //! @param [in] args コンポーネントのコンストラクタ引数
    //! @return 追加したコンポーネントの shared_ptr
    //-----------------------------------------------------------
    template <typename T, typename... Args>
    std::shared_ptr<T> AddComponent(Args&&... args)
    {
        auto comp = std::make_shared<T>(std::forward<Args>(args)...);
        m_components.push_back(comp);
        return comp;
    }

    //-----------------------------------------------------------
    //! @briefコンポーネント取得
    //! @tparam T 取得する型
    //! @return 見つかれば shared_ptr、なければ nullptr
    //-----------------------------------------------------------
    template <typename T>
    std::shared_ptr<T> GetComponent() const
    {
        for(auto& comp : m_components) {
            auto ptr = std::dynamic_pointer_cast<T>(comp);
            if(ptr)
                return ptr;
        }
        return nullptr;
    }

    //-----------------------------------------------------------
    //! @brief 初期化呼び出し
    //-----------------------------------------------------------
    void Init();

    //-----------------------------------------------------------
    //! @brief 更新呼び出し
    //-----------------------------------------------------------
    void Update();

    //-----------------------------------------------------------
    //! @brief 描画処理
    //-----------------------------------------------------------
    void Draw();

    //-----------------------------------------------------------
    //! @brief 終了呼び出し
    //-----------------------------------------------------------
    void End();

    //-----------------------------------------------------------
    //! @brief 追加描画（スクロール/ズーム対応）
    //! @param [in] scroll スクロール値
    //! @param [in] zoom ズーム値
    //-----------------------------------------------------------
    virtual void Draw(float scroll, float zoom) { OnDraw(scroll, zoom); }
    virtual void OnDraw(float scroll, float zoom) {}

protected:
    //-----------------------------------------------------------
    //! @brief オブジェクト固有の初期化処理
    //-----------------------------------------------------------
    virtual void OnInit() {}
    virtual void OnUpdate() {}
    virtual void OnDraw() {}
    virtual void OnEnd() {}

private:
    std::vector<std::shared_ptr<ComponentBase>> m_components;    //!< 保持するコンポーネント
    std::string                                 m_name;          //!< オブジェクト名
};
}    // namespace Object
