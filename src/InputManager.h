#pragma once
//============================================================================
//! @file   InputManager.h
//! @brief  入力管理ユーティリティの宣言
//! @details 全キー入力とマウス入力を管理します。
//! @author レオ
//============================================================================
#include "DxLib.h"

namespace InputManager {
//-------------------------------------------------------
//! @brief 入力状態更新（毎フレーム呼ぶ）
//-------------------------------------------------------
void Update();

//-------------------------------------------------------
//! @brief キーが押された瞬間か
// @param key 判定するキーコード
// @return true 押された瞬間
//-------------------------------------------------------
bool PushHitKey(int key);

//-------------------------------------------------------
//! @brief マウスボタン押下中判定
// @param button MOUSE_INPUT_LEFT, MOUSE_INPUT_RIGHT など
// @return true 押下中
//-------------------------------------------------------
bool CheckMouseInput(int button);

//-------------------------------------------------------
//! @brief マウスボタン押下瞬間判定
// @param button MOUSE_INPUT_LEFT, MOUSE_INPUT_RIGHT など
// @return true 押された瞬間
//-------------------------------------------------------
bool PushMouseInput(int button);

//-------------------------------------------------------
//! @brief マウスホイール回転量取得
// @return 1以上 = 奥回転, 0 = 回していない, -1以下 = 手前回転
//-------------------------------------------------------
int GetMouseWheel();

//-------------------------------------------------------
//! @brief マウスX座標取得
//-------------------------------------------------------
int GetMouseX();

//-------------------------------------------------------
//! @brief マウスY座標取得
//-------------------------------------------------------
int GetMouseY();

// 内部で使う静的変数の宣言
extern char key_buffer_[256];      //!< キー押下状態バッファ
extern int  key_frame_[256];       //!< キー押下フレームカウンタ
extern int  mouse_left_frame_;     //!< 左マウスボタン押下フレーム
extern int  mouse_right_frame_;    //!< 右マウスボタン押下フレーム
extern int  mouse_wheel_rot_;      //!< マウスホイール回転量
}    // namespace InputManager
