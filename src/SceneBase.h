#pragma once
#include "GameObject.h"
#include <vector>
#include <memory>
#include <string>

namespace Scene
{
	//-----------------------------------------------------------
	/// @brief シーン基底クラス
	/// @details シーン内のオブジェクト管理およびライフサイクルを提供
	//-----------------------------------------------------------
	class SceneBase {
	public:
		//-----------------------------------------------------------
		/// @brief シーン初期化
		//-----------------------------------------------------------
		virtual void Init();

		//-----------------------------------------------------------
		/// @brief シーン更新
		//-----------------------------------------------------------
		virtual void Update();

		//-----------------------------------------------------------
		/// @brief シーン描画
		//-----------------------------------------------------------
		virtual void Draw();

		//-----------------------------------------------------------
		/// @brief シーン終了処理
		//-----------------------------------------------------------
		virtual void End();

	protected:
		//-----------------------------------------------------------
		/// @brief シーン固有の初期化処理
		//-----------------------------------------------------------
		virtual void SceneInit() {}

		//-----------------------------------------------------------
		/// @brief シーン固有の更新処理
		//-----------------------------------------------------------
		virtual void SceneUpdate() {}

		//-----------------------------------------------------------
		/// @brief シーン固有の描画処理
		//-----------------------------------------------------------
		virtual void SceneDraw() {}

		//-----------------------------------------------------------
		/// @brief シーン固有の終了処理
		//-----------------------------------------------------------
		virtual void SceneEnd() {}

		//-----------------------------------------------------------
		/// @brief オブジェクトを追加
		/// @param obj 追加するオブジェクト(shared_ptr)
		//-----------------------------------------------------------
		void AddObject(std::shared_ptr<GameObject> obj);

		//-----------------------------------------------------------
		/// @brief オブジェクト追加
		/// @param obj_name 追加するオブジェクトの名前
		//-----------------------------------------------------------
		template <typename T>
		void AddObjectSetName(const std::string& obj_name)
		{
			auto obj = std::make_shared<T>();//オブジェクトの作成
			obj->SetName(obj_name);			 //名前の設定
			obj->Init();					 //オブジェクトの初期化処理
			scene_objects_.push_back(obj);	 //シーンにオブジェクトを追加
		}

		//-----------------------------------------------------------
		/// @brief シーン内オブジェクト取得
		/// @tparam T 取得したい型（GameObject または派生型）
		/// @param name オブジェクト名
		/// @return 見つかれば shared_ptr<T>、なければ nullptr
		//-----------------------------------------------------------
		template <typename T>
		std::shared_ptr<T> GetSceneObject(const std::string& name) const
		{
			for (const auto& obj : scene_objects_) {
				if (obj->GetName() == name) {
					return std::dynamic_pointer_cast<T>(obj);
				}
			}
			return nullptr;
		}

		//-----------------------------------------------------------
		/// @brief シーン内オブジェクトの初期化呼び出し
		//-----------------------------------------------------------
		void ObjectInit();

		//-----------------------------------------------------------
		/// @brief シーン内オブジェクトの更新呼び出し
		//-----------------------------------------------------------
		void ObjectUpdate();

		//-----------------------------------------------------------
		/// @brief シーン内オブジェクトの描画呼び出し
		//-----------------------------------------------------------
		void ObjectDraw();

		//-----------------------------------------------------------
		/// @brief シーン内オブジェクトの終了呼び出し
		//-----------------------------------------------------------
		void ObjectEnd();

		std::vector<std::shared_ptr<GameObject>> scene_objects_; //!< シーンが保持するオブジェクト
	};
}
