//============================================================================
//! @file   SceneManager.cpp
//! @brief  シーン管理の実装
//! @details 複数シーンの登録とライフサイクル一括処理を提供します。
//! @author レオ
//============================================================================
#include "SceneManager.h"

namespace Scene {
//-----------------------------------------------------------
//! @brief シーンを登録する
//-----------------------------------------------------------
void SceneManager::AddScene(std::unique_ptr<SceneBase> scene)
{
    m_scenes.push_back(std::move(scene));
}

//-----------------------------------------------------------
//! @brief 登録されている全シーンを初期化する
//-----------------------------------------------------------
void SceneManager::InitAll()
{
    for(auto& s : m_scenes) {
        s->Init();
    }
}

//-----------------------------------------------------------
//! @brief 登録されている全シーンを更新する
//-----------------------------------------------------------
void SceneManager::UpdateAll()
{
    for(auto& s : m_scenes) {
        s->Update();
    }
}

//-----------------------------------------------------------
//! @brief 登録されている全シーンを描画する
//-----------------------------------------------------------
void SceneManager::DrawAll()
{
    for(auto& s : m_scenes) {
        s->Draw();
    }
}

//-----------------------------------------------------------
//! @brief 登録されている全シーンの終了処理を行う
//-----------------------------------------------------------
void SceneManager::EndAll()
{
    for(auto& s : m_scenes) {
        s->End();
    }
    m_scenes.clear();
}
}    // namespace Scene
