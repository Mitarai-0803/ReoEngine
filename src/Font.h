#pragma once

namespace  Font
{
	//---------------------------------------------------------------------------------
	// @briefフォントサイズごとのインデックス
	// FONT_MAX はフォントの最大数
	//---------------------------------------------------------------------------------
	enum FontIndex
	{
		FONT_SIZE_70_INDEX = 0,  //!< フォントサイズ 70 のインデックス
		FONT_SIZE_50_INDEX,      //!< フォントサイズ 50 のインデックス
		FONT_SIZE_40_INDEX,      //!< フォントサイズ 40 のインデックス
		FONT_SIZE_30_INDEX,      //!< フォントサイズ 30 のインデックス
		FONT_SIZE_25_INDEX,      //!< フォントサイズ 25 のインデックス
		FONT_SIZE_10_INDEX,      //!< フォントサイズ 10 のインデックス
		FONT_MAX                 //!< フォントの最大数
	};

	//---------------------------------------------------------------------------------
	/// @brief フォント初期化
	/// @details 各サイズのフォントデータをロードし、内部のフォントハンドルに保持します。
	///          DxLib 初期化 (DxLib_Init) 後に呼び出してください。
	//---------------------------------------------------------------------------------
	void FontInit();

	//---------------------------------------------------------------------------------
	/// @brief フォント解放
	/// @details FontInit で確保したフォントハンドルをすべて解放します。
	///          アプリケーション終了時に呼び出してください。
	//---------------------------------------------------------------------------------
	void FontExit();

	//---------------------------------------------------------------------------------
	/// @brief フォントハンドル取得
	/// @param font_index フォントサイズインデックス
	/// @return 指定インデックスのフォントハンドル。範囲外の場合はデフォルトのハンドルを返す。
	//---------------------------------------------------------------------------------
	int GetFont(int font_index);

	//---------------------------------------------------------------------------------
	// フォントハンドル配列
	// @brief 各サイズのフォントハンドルを保持
	//---------------------------------------------------------------------------------
	static int font_handle[FONT_MAX] = { 0 };//!< フォントハンドル
}// namespace Font