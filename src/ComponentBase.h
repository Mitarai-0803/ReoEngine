#pragma once

//----------------------------------------------------------------------------
//! @file   ComponentBase.h
//! @brief コンポーネント基底クラスの宣言
//! @detail ゲームオブジェクトが保持するコンポーネントの共通インターフェースを定義します。
//----------------------------------------------------------------------------

//============================================================================
//! @class  ComponentBase
//! コンポーネントの基底クラスです。
//============================================================================
class ComponentBase
{
public:
	//-----------------------------------------------------------
	//! デフォルトコンストラクタ
	//-----------------------------------------------------------
	ComponentBase() = default;

	//-----------------------------------------------------------
	//! デストラクタ
	//-----------------------------------------------------------
	virtual ~ComponentBase() = default;

	//-----------------------------------------------------------
	//! 初期化処理
	//-----------------------------------------------------------
	virtual void Init() {}

	//-----------------------------------------------------------
	//! 更新処理
	//-----------------------------------------------------------
	virtual void Update() {}

	//-----------------------------------------------------------
	//! 描画処理
	//-----------------------------------------------------------
	virtual void Draw() {}

	//-----------------------------------------------------------
	//! 終了処理
	//-----------------------------------------------------------
	virtual void End() {}

private:
	// 将来の拡張用
};
