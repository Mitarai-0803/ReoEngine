#pragma once
//============================================================================
//! @file   RenderTargetManager.h
//! @brief  レンダーターゲット（バックバッファ）管理クラス宣言
//! @details 複数のレンダーターゲットを作成・管理し、描画ターゲットの切替や描画を簡易に行えるユーティリティ
//! @author レオ
//============================================================================
#include <string>           //	文字列
#include <unordered_map>    //	管理用のハッシュマップ
#include <memory>           //	スマートポインタ

namespace Graphics {
//============================================================================
//! @class RenderTargetManager
//! @brief レンダーターゲットを管理するクラス
//! @details 名前付きのレンダーターゲットを作成・管理し、描画先の切替や描画を簡単に行えるようにするユーティリティクラス
//============================================================================
class RenderTargetManager
{
public:
    //-----------------------------------------------------------
    //! @brief コンストラクタ
    //-----------------------------------------------------------
    RenderTargetManager();

    //-----------------------------------------------------------
    //! @brief デストラクタ
    //-----------------------------------------------------------
    ~RenderTargetManager();

    //-----------------------------------------------------------
    //! @brief レンダーターゲット作成
    //! @param [in] name    管理名
    //! @param [in] width   幅
    //! @param [in] height  高さ
    //! @param [in] useAlpha アルファを利用するか
    //! @return 作成したグラフィックハンドル（失敗時は -1）
    //-----------------------------------------------------------
    int CreateRenderTarget(const std::string& name, int width, int height, bool useAlpha = true);

    //-----------------------------------------------------------
    //! @brief 指定名のレンダーターゲットをアクティブにして描画先を切替
    //! @param [in] name 管理名
    //! @return true 成功
    //-----------------------------------------------------------
    bool SetActive(const std::string& name);

    //-----------------------------------------------------------
    //! @brief 描画先をスクリーン（デフォルト）に戻す
    //-----------------------------------------------------------
    void ResetToScreen();

    //-----------------------------------------------------------
    //! @brief 指定名のレンダーターゲットを画面に描画する
    //! @param [in] name 管理名
    //! @param [in] x    描画 X
    //! @param [in] y    描画 Y
    //-----------------------------------------------------------
    void Present(const std::string& name, int x = 0, int y = 0);

    //-----------------------------------------------------------
    //! @brief レンダーターゲットの解放
    //! @param [in] name 管理名
    //-----------------------------------------------------------
    void Release(const std::string& name);

    //-----------------------------------------------------------
    //! @brief 全てのレンダーターゲットを解放
    //-----------------------------------------------------------
    void ReleaseAll();

    //-----------------------------------------------------------
    //! @brief 指定名のハンドル取得（直接操作したい場合）
    //! @param [in] name 管理名
    //! @return ハンドル（存在しない場合は -1）
    //-----------------------------------------------------------
    int GetHandle(const std::string& name) const;

private:
    struct Impl;
    std::unique_ptr<Impl> m_impl;    //!< 実装のポインタ（Pimpl イディオム）
};
}    // namespace Graphics
