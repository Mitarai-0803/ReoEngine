#pragma once
#include "ComponentBase.h"
#include "Transform.h"
#include <vector>
#include <memory>
#include <type_traits>
#include <string>

//----------------------------------------------------------------------------
//! @file   GameObject.h
//! @brief ゲームオブジェクトの宣言
//! @detail ゲームオブジェクトは複数のコンポーネントを保持し、ライフサイクル制御を行います。
//----------------------------------------------------------------------------

//============================================================================
//! @class  GameObject
//! ゲームオブジェクトを表現するクラスです。
//============================================================================
class GameObject {
public:
    //-----------------------------------------------------------
    //! デフォルトコンストラクタ
    //-----------------------------------------------------------
    GameObject() = default;

    //-----------------------------------------------------------
    //! デストラクタ
    //-----------------------------------------------------------
    ~GameObject();

    //-----------------------------------------------------------
    //! オブジェクト名を取得
    //! @return 取得したオブジェクト名
    //-----------------------------------------------------------
    const std::string& GetName() const { return name_; }

    //-----------------------------------------------------------
    //! オブジェクト名を設定
    //! @param  [in] name オブジェクト名
    //-----------------------------------------------------------
    void SetName(const std::string& name) { name_ = name; }

    //-----------------------------------------------------------
    //! ワールド変換を取得
    //! @return Transform の参照
    //-----------------------------------------------------------
    Transform& GetTransform() { return transform_; }

    //-----------------------------------------------------------
    //! コンポーネントを追加して初期化
    //! @tparam T 追加するコンポーネントの型
    //! @param  args コンポーネントのコンストラクタ引数
    //! @return 追加されたコンポーネントの共有ポインタ
    //-----------------------------------------------------------
    template <typename T, typename... Args>
    std::shared_ptr<T> AddComponent(Args&&... args) {
        auto comp = std::make_shared<T>(std::forward<Args>(args)...);
        comp->Init();
        components_.push_back(comp);
        return comp;
    }

    //-----------------------------------------------------------
    //! 指定型のコンポーネントを取得
    //! @tparam T 取得するコンポーネントの型
    //! @return 見つかったコンポーネントの共有ポインタ、存在しない場合はnullptr
    //-----------------------------------------------------------
    template<typename T>
    std::shared_ptr<T> GetComponent() const {
        for (auto const& comp : components_) {
            auto ptr = std::dynamic_pointer_cast<T>(comp);
            if (ptr) return ptr;
        }
        return nullptr;
    }

    //-----------------------------------------------------------
    //! 全コンポーネントの初期化処理
    //-----------------------------------------------------------
    void Init();

    //-----------------------------------------------------------
    //! 全コンポーネントの更新処理
    //-----------------------------------------------------------
    void Update();

    //-----------------------------------------------------------
    //! 全コンポーネントの描画処理
    //-----------------------------------------------------------
    void Draw();

    //-----------------------------------------------------------
    //! 全コンポーネントの終了処理
    //-----------------------------------------------------------
    void End();

    //-----------------------------------------------------------
    //! 拡張描画（スクロール・ズーム対応）
    //! @param  [in] scroll スクロール量
    //! @param  [in] zoom   ズーム倍率
    //-----------------------------------------------------------
    virtual void Draw(float scroll, float zoom) { OnDraw(scroll, zoom); }
    virtual void OnDraw(float scroll, float zoom) {}

protected:
    virtual void OnInit() {}
    virtual void OnUpdate() {}
    virtual void OnDraw() {}
    virtual void OnEnd() {}

private:
    std::vector<std::shared_ptr<ComponentBase>> components_; //!< 保持するコンポーネント
    Transform transform_; //!< ワールド変換
    std::string name_; //!< オブジェクト名
};
