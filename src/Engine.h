#pragma once
//============================================================================
//! @file   Engine.h
//! @brief  エンジンコアの宣言
//! @details ObjectBase のライフサイクルを管理するクラス群を提供します。
//! @author レオ
//============================================================================
#include "ObjectBase.h"    // ObjectBase クラスの宣言
#include <vector>          // ベクタコンテナ
#include <memory>          // スマートポインタ

namespace Engine {

//============================================================================
//! @class  Engine
//! @brief ObjectBase のライフサイクルを一括管理するクラス
//! @details ゲームオブジェクトの生成、更新、描画、終了処理を統括的に管理します。
//============================================================================
class Engine
{
public:
    //-------------------------------------------------------
    //! @brief ObjectBase を追加する
    // @param obj 追加する ObjectBase
    //-------------------------------------------------------
    void AddObject(std::shared_ptr<Object::ObjectBase> obj);

    //-------------------------------------------------------
    //! @brief 登録されている ObjectBase をすべて更新する
    //-------------------------------------------------------
    void UpdateAll();

    //-------------------------------------------------------
    //! @brief 登録されている ObjectBase をすべて描画する
    //-------------------------------------------------------
    void DrawAll();

    //-------------------------------------------------------
    //! @brief 登録されている ObjectBase の終了処理をすべて呼び出す
    //-------------------------------------------------------
    void EndAll();

private:
    std::vector<std::shared_ptr<Object::ObjectBase>> m_game_objects;    //!< 登録されている ObjectBase の一覧
};
}    // namespace Engine
