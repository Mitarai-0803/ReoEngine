#pragma once
//============================================================================
//! @file   SceneManager.h
//! @brief  シーン管理クラスの宣言
//! @details 複数シーンの登録とライフサイクル一括処理を提供します。
//! @author レオ
//============================================================================
#include "SceneBase.h"
#include <vector>
#include <memory>

namespace Scene {
//============================================================================
//! @class SceneManager
//! @brief シーンの登録と一括処理を行うマネージャ
//============================================================================
class SceneManager
{
public:
    //-----------------------------------------------------------
    //! @brief シーンを登録します（所有権を受け取る）
    //! @param scene 登録するシーン（unique_ptr）
    //-----------------------------------------------------------
    void AddScene(std::unique_ptr<SceneBase> scene);

    //-----------------------------------------------------------
    //! @brief 登録されている全シーンを初期化します
    //-----------------------------------------------------------
    void InitAll();

    //-----------------------------------------------------------
    //! @brief 登録されている全シーンを更新します
    //-----------------------------------------------------------
    void UpdateAll();

    //-----------------------------------------------------------
    //! @brief 登録されている全シーンを描画します
    //-----------------------------------------------------------
    void DrawAll();

    //-----------------------------------------------------------
    //! @brief 登録されている全シーンの終了処理を行います
    //-----------------------------------------------------------
    void EndAll();

private:
    std::vector<std::unique_ptr<SceneBase>> m_scenes;    //!< 登録されたシーン一覧（所有権は unique_ptr）
};
}    // namespace Scene
