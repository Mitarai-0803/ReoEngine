//============================================================================
//! @file   ObjectBase.cpp
//! @brief  ゲームオブジェクトの実装
//! @details コンポーネントを保持し、ライフサイクルを管理するクラスの実装を提供します。
//! @author レオ
//============================================================================
#include "ObjectBase.h"    // ヘッダーファイルのインクルード

namespace Object {
//-----------------------------------------------------------
//! @brief 初期化処理
//-----------------------------------------------------------
void ObjectBase::Init()
{
    // コンポーネントの初期化呼び出し
    for(auto& comp : m_components) {
        comp->Init();
    }
    OnInit();    // オブジェクト固有の初期化
}

//-----------------------------------------------------------
//! @brief 更新処理
//-----------------------------------------------------------
void ObjectBase::Update()
{
    for(auto& comp : m_components) {
        comp->Update();
    }
    OnUpdate();    // オブジェクト固有の更新処理
}

//-----------------------------------------------------------
//! @brief 描画処理
//-----------------------------------------------------------
void ObjectBase::Draw()
{
    for(auto& comp : m_components) {
        comp->Draw();
    }
    OnDraw();    // オブジェクト固有の描画処理
}

//-----------------------------------------------------------
//! @brief 終了処理
//-----------------------------------------------------------
void ObjectBase::End()
{
    for(auto& comp : m_components) {
        comp->End();
    }
    m_components.clear();
    OnEnd();    // オブジェクト固有の終了処理
}

//-----------------------------------------------------------
//! @brief デストラクタ
//-----------------------------------------------------------
ObjectBase::~ObjectBase()
{
    End();    // 終了処理を呼ぶ
}
}    // namespace Object
