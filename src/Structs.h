#pragma once

//-----------------------------------------------------------
/// @brief 2D位置（float）
//-----------------------------------------------------------
struct FloatPos
{
    float x = 0.0f; //!< X位置
    float y = 0.0f; //!< Y位置
};

//-----------------------------------------------------------
/// @brief 2D位置（int）
//-----------------------------------------------------------
struct IntPos
{
    int x = 0; //!< X位置
    int y = 0; //!< Y位置
};

//-----------------------------------------------------------
/// @brief サイズ（float）
//-----------------------------------------------------------
struct FloatSize
{
    float w = 0.0f; //!< 幅
    float h = 0.0f; //!< 高さ
};

//-----------------------------------------------------------
/// @brief サイズ（int）
//-----------------------------------------------------------
struct IntSize
{
    int w = 0; //!< 幅
    int h = 0; //!< 高さ
};

//-----------------------------------------------------------
/// @brief 画像入力情報（float）
//-----------------------------------------------------------
struct ImageInputF
{
    int image = 0;   //!< 画像ハンドル
    float w = 0.0f;  //!< 幅
    float h = 0.0f;  //!< 高さ
    float rot = 0.0f; //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
/// @brief 画像入力情報（int）
//-----------------------------------------------------------
struct ImageInputI
{
    int image = 0;   //!< 画像ハンドル
    int w = 0;       //!< 幅
    int h = 0;       //!< 高さ
    float rot = 0.0f; //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
/// @brief 画像プロパティ（float）
//-----------------------------------------------------------
struct ImagePropertyF
{
    FloatPos pos; //!< 位置
    int image = 0; //!< 画像ハンドル
    int w = 0;    //!< 幅
    int h = 0;    //!< 高さ
    float rot = 0.0f; //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
/// @brief ボックス（float）
//-----------------------------------------------------------
struct BoxF
{
    float x = 0.0f; //!< 左上X
    float y = 0.0f; //!< 左上Y
    float w = 0.0f; //!< 幅
    float h = 0.0f; //!< 高さ
};

//-----------------------------------------------------------
/// @brief ボックス（int）
//-----------------------------------------------------------
struct BoxI
{
    int x = 0; //!< 左上X
    int y = 0; //!< 左上Y
    int w = 0; //!< 幅
    int h = 0; //!< 高さ
};

//-----------------------------------------------------------
/// @brief カラー
//-----------------------------------------------------------
struct RGB
{
	int r = 0; //!< 赤
	int g = 0; //!< 緑
	int b = 0; //!< 青
};
